; ---------------- AUTOMATIC BILL ----------------

GENERATE_BILL PROC

    CLEAR_SCREEN
    PAGE_TITLE BILL_TITLE

    CMP CART_COUNT,0
    JE BILL_EMPTY

    MOV SUBTOTAL,0
    MOV TOTAL_ITEMS,0
    MOV SI,0

BILL_LOOP:

    MOV AX,0
    MOV AL,CART_COUNT
    CMP SI,AX
    JAE BILL_CALCULATED

    MOV AX,SI
    MOV TEMP_CART_INDEX,AL

    MOV AL,CART_BOOK_IDS[SI]
    CALL FIND_BOOK_INDEX
    MOV TEMP_BOOK_INDEX,BL

    MOV AL,TEMP_BOOK_INDEX
    MOV AH,0
    MOV BX,AX

    MOV AL,BOOK_PRICES[BX]
    MOV AH,0
    MOV DI,AX

    MOV AL,TEMP_CART_INDEX
    MOV AH,0
    MOV SI,AX

    MOV BL,CART_QUANTITY[SI]
    MOV BH,0

    MOV AX,DI
    MUL BX
    ADD SUBTOTAL,AX

    MOV AL,CART_QUANTITY[SI]
    ADD TOTAL_ITEMS,AL

    MOV AL,TEMP_CART_INDEX
    MOV AH,0
    MOV SI,AX
    INC SI

    JMP BILL_LOOP


BILL_CALCULATED:

    MOV DISCOUNT,0

    CMP CURRENT_BRACU,1
    JNE BILL_NO_DISCOUNT

    CMP TOTAL_ITEMS,3
    JAE BILL_APPLY_DISCOUNT
    JMP BILL_NO_DISCOUNT


BILL_APPLY_DISCOUNT:

    MOV AX,SUBTOTAL
    MOV DX,0
    MOV BX,5
    DIV BX
    MOV DISCOUNT,AX


BILL_NO_DISCOUNT:

    MOV AX,SUBTOTAL
    SUB AX,DISCOUNT
    MOV FINAL_TOTAL,AX

    PRINT_STRING TOTAL_ITEM_MESSAGE
    MOV AL,TOTAL_ITEMS
    MOV AH,0
    CALL PRINT_NUMBER
    NEW_LINE
    NEW_LINE

    PRINT_STRING BILL_SUBTOTAL
    MOV AX,SUBTOTAL
    CALL PRINT_NUMBER
    NEW_LINE

    PRINT_STRING BILL_DISCOUNT
    MOV AX,DISCOUNT
    CALL PRINT_NUMBER
    NEW_LINE

    PRINT_STRING BILL_FINAL
    MOV AX,FINAL_TOTAL
    CALL PRINT_NUMBER
    NEW_LINE
    NEW_LINE

    CMP DISCOUNT,0
    JE BILL_NO_DISCOUNT_MESSAGE

    PRINT_STRING DISCOUNT_APPLIED
    NEW_LINE
    JMP BILL_MESSAGE_DONE


BILL_NO_DISCOUNT_MESSAGE:

    PRINT_STRING NO_DISCOUNT
    NEW_LINE


BILL_MESSAGE_DONE:

    NEW_LINE
    PRINT_STRING BILL_READY
    NEW_LINE
    CALL WAIT_FOR_ZERO
    RET


BILL_EMPTY:

    PRINT_STRING CART_EMPTY
    NEW_LINE
    CALL WAIT_FOR_ZERO
    RET

GENERATE_BILL ENDP



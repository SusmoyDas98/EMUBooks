CHECK_BRACU_EMAIL PROC
    MOV AL, 0
    MOV BL, EMAIL_BUFFER + 1
    CMP BL, 14
    JB NOT_BRACU

    LEA SI, EMAIL_BUFFER
    INC SI
    INC SI

    MOV AL, EMAIL_BUFFER + 1
    SUB AL, 14
    MOV AH, 0
    ADD SI, AX

    LEA DI, BRACU_DOMAIN
    MOV CX, 14

CHECK_DOMAIN:
    MOV AL, [SI]
    CMP AL, [DI]
    JNE NOT_BRACU

    INC SI
    INC DI
    LOOP CHECK_DOMAIN

    MOV AL, 1
    RET

NOT_BRACU:
    MOV AL, 0
    RET
CHECK_BRACU_EMAIL ENDP



STORE_SIGNUP_USER PROC
    
    ; TOTAL NUMBER OF USERS
    MOV AL, TOTAL_USERS
    MOV AH, 0
     
    MOV BL, 100
    MUL BL
 
    MOV DI, AX
    
    ; STORING EMAIL
    
    LEA SI, EMAIL_BUFFER
    INC SI
    
    MOV CL, EMAIL_BUFFER + 1
    MOV CH, 0
    
    STORE_EMAIL:
    CMP CX, 0
    JE EMAIL_DONE
    
    MOV AL, [SI]
    MOV EMAIL_STORAGE[DI], AL
    
    INC SI
    INC DI
    
    DEC CX
    JMP STORE_EMAIL
    
    EMAIL_DONE:
    
    MOV AL, TOTAL_USERS
    MOV AH, 0
    
    MOV BL, 100
    MUL BL
    
    MOV DI, AX
    
    ; STORING PASSWORD 
    
    LEA SI, PASSWORD_BUFFER
    
    INC SI
    
    MOV CL, PASSWORD_BUFFER + 1
    MOV CH, 0
    
    STORE_PASSWORD:
    CMP CX, 0
    JE PASSWORD_DONE
    
    MOV AL, [SI]
    MOV PASSWORD_STORAGE[DI], AL
    
    INC SI
    INC DI
    
    DEC CX
    
    JMP STORE_PASSWORD
    
    PASSWORD_DONE:
    CALL CHECK_BRACU_EMAIL
    
    MOV BL, TOTAL_USERS
    MOV BH, 0
    
    MOV IS_BRACU[BX], AL
    
    ;ADDING NEW USER
    
    INC TOTAL_USERS
 
    
    RET
STORE_SIGNUP_USER ENDP          



CHECK_LOGIN_USER  PROC                
    MOV USER_FOUND ,0
    MOV BL, 0
    MOV BH, 0
    
    CHECK_USER_LOOP:
        ; CHECKING IF ANY USER AVAILABLE
        CMP BL, TOTAL_USERS
        JE LOGIN_NOT_FOUND
        
        ; FINDING STORAGE POSITION
        
        MOV AL,BL
        MOV AH, 0
        
        MOV DL, 100
        MUL DL
        
        MOV DI, AX
        
        ; CHECKING EMAIL
        
        LEA SI, EMAIL_BUFFER
        INC SI
        
        MOV CL, EMAIL_BUFFER + 1
        
        MOV CH, 0
        
     CHECK_EMAIL:
        CMP CX, 0
        JE EMAIL_CHECK_DONE
        
        MOV AL, [SI]
        CMP AL, EMAIL_STORAGE[DI]
        JNE NEXT_USER
        
        INC SI
        INC DI
        
        DEC CX
        JMP CHECK_EMAIL
        
     EMAIL_CHECK_DONE:
        ; FINDING PASSWORD AND STORAGE POSITION
        
        MOV AL, BL
        MOV AH, 0
        
        MOV DL, 100
        MUL DL
        
        MOV DI, AX
        
        ; CHEKING PASSWORD 
        
        LEA SI, PASSWORD_BUFFER
        INC SI
        
        MOV CL,PASSWORD_BUFFER + 1
        MOV CH, 0
        
     CHECK_PASSWORD:
        CMP CX, 0
        JE LOGIN_FOUND          
        
        MOV AL, [SI]
        CMP AL, PASSWORD_STORAGE[DI]
        JNE NEXT_USER
        
        INC SI
        INC DI
        
        DEC  CX
        
        JMP CHECK_PASSWORD
        
     LOGIN_FOUND:
        MOV USER_FOUND ,1
        MOV LOGGED_USER_INDEX, BL
        RET
        
     NEXT_USER:
        INC BL
        JMP CHECK_USER_LOOP
        
     LOGIN_NOT_FOUND:
        MOV USER_FOUND, 0  
        
    
    RET
CHECK_LOGIN_USER ENDP




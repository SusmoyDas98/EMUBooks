; ---------------- FIND BOOK ----------------
; Input: AL = Book ID
; Output: BX = book index, BOOK_FOUND = 1 if found

FIND_BOOK_INDEX PROC

    MOV BOOK_FOUND,0
    MOV DL,AL
    MOV SI,0

FIND_BOOK_LOOP:
    MOV AX,0
    MOV AL,TOTAL_BOOKS
    CMP SI,AX
    JAE FIND_BOOK_END

    MOV AL,DL
    CMP AL,BOOK_IDS[SI]
    JE FIND_BOOK_FOUND

    INC SI
    JMP FIND_BOOK_LOOP

FIND_BOOK_FOUND:
    MOV BX,SI
    MOV BOOK_FOUND,1

FIND_BOOK_END:
    RET

FIND_BOOK_INDEX ENDP


; ---------------- FIND CART ITEM ----------------
; Input: AL = Book ID
; Output: BX = cart index, CART_FOUND = 1 if found

FIND_CART_ITEM PROC

    MOV CART_FOUND,0
    MOV DL,AL
    MOV SI,0

FIND_CART_LOOP:
    MOV AX,0
    MOV AL,CART_COUNT
    CMP SI,AX
    JAE FIND_CART_END

    MOV AL,DL
    CMP AL,CART_BOOK_IDS[SI]
    JE FIND_CART_FOUND

    INC SI
    JMP FIND_CART_LOOP

FIND_CART_FOUND:
    MOV BX,SI
    MOV CART_FOUND,1

FIND_CART_END:
    RET

FIND_CART_ITEM ENDP


; ---------------- ADD BOOK TO CART ----------------

ADD_TO_CART PROC

    CLEAR_SCREEN
    PAGE_TITLE CART_MENU_TITLE

ADD_BOOK_INPUT:
    PRINT_STRING BOOK_ID_INPUT
    INPUT_INT
    SUB AL,48
    MOV TEMP_BOOK_ID,AL
    NEW_LINE

    MOV AL,TEMP_BOOK_ID
    CALL FIND_BOOK_INDEX

    CMP BOOK_FOUND,1
    JE ADD_BOOK_ID_OK

    PRINT_STRING INVALID_BOOK
    NEW_LINE
    PRINT_STRING GIVE_INPUT_AGAIN
    NEW_LINE
    JMP ADD_BOOK_INPUT

ADD_BOOK_ID_OK:
    MOV TEMP_BOOK_INDEX,BL

    MOV BL,TEMP_BOOK_INDEX
    MOV BH,0

    MOV AL,BOOK_STOCK[BX]
    CMP AL,0
    JE ADD_OUT_OF_STOCK

    MOV AL,TEMP_BOOK_ID
    CALL FIND_CART_ITEM

    CMP CART_FOUND,1
    JE ADD_EXISTING_BOOK

    MOV AL,CART_COUNT
    CMP AL,MAX_CART_ITEMS
    JAE CART_IS_FULL

    MOV AL,CART_COUNT
    MOV AH,0
    MOV SI,AX

    MOV AL,TEMP_BOOK_ID
    MOV CART_BOOK_IDS[SI],AL

ADD_NEW_QUANTITY:
    PRINT_STRING QUANTITY_INPUT
    INPUT_INT
    SUB AL,48
    MOV TEMP_QUANTITY,AL
    NEW_LINE

    MOV AL,TEMP_QUANTITY
    CMP AL,1
    JB ADD_INVALID_NEW_QUANTITY
    CMP AL,9
    JA ADD_INVALID_NEW_QUANTITY
    JMP ADD_NEW_QTY_OK

ADD_INVALID_NEW_QUANTITY:
    PRINT_STRING INVALID_QUANTITY
    NEW_LINE
    PRINT_STRING GIVE_INPUT_AGAIN
    NEW_LINE
    JMP ADD_NEW_QUANTITY

ADD_NEW_QTY_OK:

    MOV BL,TEMP_BOOK_INDEX
    MOV BH,0

    CMP AL,BOOK_STOCK[BX]
    JA ADD_NOT_ENOUGH_STOCK

    MOV AL,TEMP_QUANTITY
    MOV CART_QUANTITY[SI],AL

    INC CART_COUNT

    PRINT_STRING BOOK_ADDED
    NEW_LINE
    JMP ADD_CART_DONE

ADD_EXISTING_BOOK:

    MOV TEMP_CART_INDEX,BL

ADD_EXISTING_QUANTITY:
    PRINT_STRING QUANTITY_INPUT
    INPUT_INT
    SUB AL,48
    MOV TEMP_QUANTITY,AL
    NEW_LINE

    MOV AL,TEMP_QUANTITY
    CMP AL,1
    JB ADD_INVALID_EXISTING_QUANTITY
    CMP AL,9
    JA ADD_INVALID_EXISTING_QUANTITY
    JMP ADD_EXISTING_QTY_OK

ADD_INVALID_EXISTING_QUANTITY:
    PRINT_STRING INVALID_QUANTITY
    NEW_LINE
    PRINT_STRING GIVE_INPUT_AGAIN
    NEW_LINE
    JMP ADD_EXISTING_QUANTITY

ADD_EXISTING_QTY_OK:

    MOV AL,TEMP_CART_INDEX
    MOV AH,0
    MOV SI,AX

    MOV AL,CART_QUANTITY[SI]
    MOV BL,TEMP_QUANTITY
    ADD AL,BL
    MOV TEMP_QUANTITY,AL

    MOV BL,TEMP_BOOK_INDEX
    MOV BH,0

    CMP AL,BOOK_STOCK[BX]
    JA ADD_NOT_ENOUGH_STOCK

    MOV AL,TEMP_QUANTITY
    MOV CART_QUANTITY[SI],AL

    PRINT_STRING BOOK_ADDED
    NEW_LINE
    JMP ADD_CART_DONE

ADD_OUT_OF_STOCK:
    PRINT_STRING OUT_OF_STOCK
    NEW_LINE
    JMP ADD_CART_DONE

ADD_NOT_ENOUGH_STOCK:
    PRINT_STRING NOT_ENOUGH_STOCK
    NEW_LINE
    JMP ADD_CART_DONE

CART_IS_FULL:
    PRINT_STRING CART_FULL
    NEW_LINE

ADD_CART_DONE:
ADD_CART_BACK:
    PRINT_STRING PRESS_BACK
    NEW_LINE
    INPUT_INT
    CMP AL,'0'
    JE ADD_CART_RETURN  
     
    NEW_LINE
    PRINT_STRING INVALID_INPUT
    NEW_LINE
    PRINT_STRING GIVE_INPUT_AGAIN
    NEW_LINE
    JMP ADD_CART_BACK

ADD_CART_RETURN:
    RET

ADD_TO_CART ENDP


; ---------------- REMOVE BOOK FROM CART ----------------

REMOVE_FROM_CART PROC

    CLEAR_SCREEN
    PAGE_TITLE CART_MENU_TITLE

    CMP CART_COUNT,0
    JE REMOVE_EMPTY

    PRINT_STRING BOOK_ID_INPUT
    INPUT_INT
    SUB AL,48
    MOV TEMP_BOOK_ID,AL
    NEW_LINE

    MOV AL,TEMP_BOOK_ID
    CALL FIND_CART_ITEM

    CMP CART_FOUND,1
    JNE REMOVE_NOT_FOUND

    MOV TEMP_CART_INDEX,BL

    MOV AL,TEMP_CART_INDEX
    MOV AH,0
    MOV SI,AX

    MOV DI,SI
    INC DI

REMOVE_SHIFT_LOOP:
    MOV AX,0
    MOV AL,CART_COUNT
    CMP DI,AX
    JAE REMOVE_SHIFT_DONE

    MOV AL,CART_BOOK_IDS[DI]
    MOV CART_BOOK_IDS[SI],AL

    MOV AL,CART_QUANTITY[DI]
    MOV CART_QUANTITY[SI],AL

    INC SI
    INC DI
    JMP REMOVE_SHIFT_LOOP

REMOVE_SHIFT_DONE:
    DEC CART_COUNT

    PRINT_STRING BOOK_REMOVED
    NEW_LINE
    JMP REMOVE_DONE

REMOVE_EMPTY:
    PRINT_STRING CART_EMPTY
    NEW_LINE
    JMP REMOVE_DONE

REMOVE_NOT_FOUND:
    PRINT_STRING BOOK_NOT_IN_CART
    NEW_LINE

REMOVE_DONE:
    CALL WAIT_FOR_ZERO
    RET

REMOVE_FROM_CART ENDP



; ---------------- PRINT MULTI-DIGIT NUMBER ----------------
; Input: AX = number

PRINT_NUMBER PROC

    CMP AX,0
    JNE PRINT_NUMBER_START

    MOV DL,'0'
    MOV AH,2
    INT 21H
    RET

PRINT_NUMBER_START:

    MOV BX,10
    MOV CX,0

PRINT_NUMBER_DIVIDE:

    MOV DX,0
    DIV BX

    PUSH DX
    INC CX

    CMP AX,0
    JNE PRINT_NUMBER_DIVIDE

PRINT_NUMBER_OUTPUT:

    POP DX
    ADD DL,48

    MOV AH,2
    INT 21H

    LOOP PRINT_NUMBER_OUTPUT

    RET

PRINT_NUMBER ENDP


